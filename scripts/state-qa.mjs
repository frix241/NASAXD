import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,channel:'chromium',args:['--enable-gpu','--use-gl=angle','--use-angle=gl']});
const context=await browser.newContext();const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/?qa=1');
await page.getByRole('radio',{name:'Aislar Cuerpo holográfico',exact:true}).click();
await page.reload();await page.getByRole('radio',{name:'Aislar Cuerpo holográfico',exact:true}).waitFor();
assert.equal(await page.getByRole('radio',{name:'Aislar Cuerpo holográfico',exact:true}).getAttribute('aria-checked'),'true');
await page.getByRole('radio',{name:'Aislar Órganos internos',exact:true}).click();
await page.waitForFunction(()=>window.__ASTROTWIN_QA__?.layers.organs===true);
await page.getByLabel('Explorar órgano',{exact:true}).selectOption('suit');
await page.getByText('Seleccionado: Traje biométrico',{exact:true}).waitFor();
await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true}));});
await context.setOffline(true);await page.reload();await page.getByRole('heading',{name:'Tu cuerpo. Tu misión.',exact:true}).waitFor();
await page.waitForFunction(()=>window.__ASTROTWIN_QA__?.layers.suit===true);
assert.deepEqual(errors,[]);
await writeFile('artifacts/state-qa.json',JSON.stringify({passed:true,checks:['Preset coherente con preferencias persistidas','Vista de órganos después de recarga','Selección de traje preserva contexto','Recarga offline del build final'],errors},null,2));
console.log('PASS 4 regresiones de estado/offline');await browser.close();
